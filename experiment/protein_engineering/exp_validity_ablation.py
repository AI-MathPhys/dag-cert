"""Experiment v11-1 (P0): Real-Data Certificate-Validity & Acquisition-vs-Stopping Ablation.

Directly resolves the central statistical validity question on real combinatorial protein
landscapes (GB1: 10 templates x 20 seeds = 200 paired runs; TmTrpB: 21 templates x 10 seeds
= 210 paired runs; eps = 0.015, delta = 0.05, caps 12k & 25k):

  "Do the 3--5x sample-complexity gains over Optimistic-Separation survive when the final
   stopping certificate has a justified formal guarantee for the actual observation model,
   or do those gains come primarily from the tighter empirically calibrated (model-based)
   GP/EB+LOO stopping ellipsoid?"

Part A — Full Interactive Acquisition x Certificate-Validity Factorial (9 methods, paired seeds):
  Formal Distribution-Free Stopping (Empirical Bernstein [0, 1] box, zero model assumptions):
    1. `os_df_stop`              : OS acquisition + DF Empirical Bernstein stopping (baseline)
    2. `eb_pure_df_stop`         : Pure EB+LOO contrast-directed acquisition + DF EB stopping ONLY
    3. `eb_warmup_os_df_stop`    : EB+LOO warmup (300 pulls) + OS exterior witness + DF EB stopping ONLY
    4. `gp_root_info_df_stop`    : EB-calibrated GP-Root-Info acquisition + DF EB stopping ONLY
    5. `eb_acq_eb_and_df_strict` : STRICT INTERSECTION — EB+LOO stops discovery, then OS confirms
                                   until BOTH EB+LOO and DF EB certify (100% formally DF valid!)
  Model-Dependent Bounded-Residual Stopping (Valid under |bias| <= xi = 0.005):
    6. `eb_acq_rob005_stop`      : EB+LOO acquisition + bounded-residual xi=0.005 ellipsoid stopping
    7. `eb_acq_rob005_or_df`     : Valid (delta/2) xi=0.005 ellipsoid OR (delta/2) DF EB fallback
  Empirically Calibrated / Model-Based Stopping (NOT formally distribution-free):
    8. `eb_acq_nom_stop`         : Nominal GP acquisition + unadjusted nominal GP ellipsoid stopping
    9. `eb_acq_eb_stop`          : EB+LOO acquisition + empirically calibrated EB+LOO ellipsoid stopping

Part B — Exact Fixed-Trajectory Coupled-Stream Replay (holding the observation stream IDENTICAL):
  Replays four stopping rules (`DF_EmpBernstein`, `Robust_xi005`, `Nominal_GP`, `Calibrated_EBLOO`)
  on the EXACT same observation trajectories generated by (i) `os_df_stop` and (ii) pure `EB+LOO`
  acquisition up to 25k assays, cleanly isolating stopping-rule tightness from acquisition quality
  with zero Monte Carlo confounding, and measuring exact pointwise vs. decision-regret coverage of
  the GP ellipsoids against the true landscape fitness vectors!

Statistical Rigor:
  - Reports exact empirical error rates `k/n` + exact Clopper-Pearson 95% upper confidence bounds.
  - Reports censored completion rates at 12k & 25k, censored medians/IQRs, and uncertified regrets.
  - Reports 10,000-resample paired bootstrap 95% CIs across paired `(template, seed)` units.
  - Never reports uncensored speedup ratios against censored 12k caps (paired speedup ratios are
    reported ONLY at 25k where `os_df_stop` achieves 100% completion!).
"""
